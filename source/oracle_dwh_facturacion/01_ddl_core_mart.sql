CREATE SEQUENCE DWH_CORE.SEQ_DIM_CLIENTE START WITH 1 INCREMENT BY 1 CACHE 1000 NOCYCLE;

CREATE TABLE DWH_CORE.DIM_CLIENTE (
    SK_CLIENTE              NUMBER(12)      NOT NULL,
    ID_CLIENTE              NUMBER(10)      NOT NULL,
    NIF                     VARCHAR2(12),
    NOMBRE                  VARCHAR2(200),
    SEGMENTO                VARCHAR2(20),
    PROVINCIA               VARCHAR2(50),
    ID_CLIENTE_PADRE        NUMBER(10),
    FECHA_ALTA              DATE,
    FECHA_INICIO_VIGENCIA   DATE            DEFAULT SYSDATE NOT NULL,
    FECHA_FIN_VIGENCIA      DATE            DEFAULT TO_DATE('31/12/9999','DD/MM/YYYY'),
    ES_ACTUAL               CHAR(1)         DEFAULT 'S',
    HASH_ATRIBUTOS          VARCHAR2(64),
    CONSTRAINT PK_DIM_CLIENTE PRIMARY KEY (SK_CLIENTE)
) TABLESPACE TBS_DWH_CORE;

CREATE BITMAP INDEX DWH_CORE.IX_DIM_CLIENTE_SEG ON DWH_CORE.DIM_CLIENTE (SEGMENTO) TABLESPACE TBS_DWH_IDX;
CREATE INDEX DWH_CORE.IX_DIM_CLIENTE_ID ON DWH_CORE.DIM_CLIENTE (ID_CLIENTE, ES_ACTUAL) TABLESPACE TBS_DWH_IDX;

CREATE TABLE DWH_CORE.FACT_TRAFICO_DIARIO (
    FECHA                   DATE            NOT NULL,
    ID_LINEA                NUMBER(12)      NOT NULL,
    ID_CLIENTE              NUMBER(10)      NOT NULL,
    COD_TARIFA              VARCHAR2(10),
    MINUTOS_VOZ             NUMBER(12,2)    DEFAULT 0,
    MB_DATOS                NUMBER(14,3)    DEFAULT 0,
    NUM_SMS                 NUMBER(8)       DEFAULT 0,
    MINUTOS_ROAMING         NUMBER(12,2)    DEFAULT 0,
    IMPORTE_FUERA_BONO      NUMBER(12,4)    DEFAULT 0,
    PCT_CONSUMO_BONO_DATOS  NUMBER(6,2),
    FECHA_CARGA             DATE            DEFAULT SYSDATE
)
PARTITION BY RANGE (FECHA) INTERVAL (NUMTODSINTERVAL(1,'DAY'))
( PARTITION P_INICIAL VALUES LESS THAN (TO_DATE('01/01/2020','DD/MM/YYYY')) )
COMPRESS FOR QUERY HIGH
TABLESPACE TBS_DWH_FACT;

CREATE TABLE DWH_CORE.FACT_FACTURACION_MENSUAL (
    PERIODO                 VARCHAR2(6)     NOT NULL,
    ID_CLIENTE              NUMBER(10)      NOT NULL,
    SEGMENTO                VARCHAR2(20),
    NUM_LINEAS_ACTIVAS      NUMBER(6),
    IMPORTE_BASE            NUMBER(14,2),
    IMPORTE_TOTAL           NUMBER(14,2),
    IMPORTE_IMPAGADO        NUMBER(14,2),
    ARPU                    NUMBER(12,2),
    MESES_ANTIGUEDAD        NUMBER(6),
    FECHA_CARGA             DATE            DEFAULT SYSDATE,
    CONSTRAINT PK_FACT_FACT_MENS PRIMARY KEY (PERIODO, ID_CLIENTE)
)
PARTITION BY LIST (PERIODO) AUTOMATIC
( PARTITION P_202001 VALUES ('202001') )
TABLESPACE TBS_DWH_FACT;

CREATE TABLE DWH_CORE.LOG_PROCESOS (
    ID_EJECUCION            NUMBER(12)      GENERATED ALWAYS AS IDENTITY,
    PROCESO                 VARCHAR2(100),
    PASO                    VARCHAR2(100),
    ESTADO                  VARCHAR2(10),
    FILAS_AFECTADAS         NUMBER(12),
    MENSAJE                 VARCHAR2(4000),
    FECHA_HORA              TIMESTAMP       DEFAULT SYSTIMESTAMP
) TABLESPACE TBS_DWH_CORE;

CREATE TABLE DWH_MART.MART_ARPU_SEGMENTO (
