/* KPIs de campanas y top 2 campanas por canal (dashboard de Marketing en MicroStrategy) */
REPLACE VIEW EDW_MKT.V_KPI_CAMPANAS AS
LOCKING ROW FOR ACCESS
SEL C.ID_CAMPANA,
    C.NOMBRE_CAMPANA,
    C.CANAL,
    C.COSTE_TOTAL,
    COUNT(*)                                                         AS CONTACTOS,
    SUM(CASE WHEN R.IND_RESPUESTA = 'S' THEN 1 ELSE 0 END)           AS RESPUESTAS,
    CAST(RESPUESTAS AS DECIMAL(9,4)) / NULLIFZERO(CONTACTOS)          AS TASA_RESPUESTA,
    ZEROIFNULL(SUM(R.IMPORTE_VENTA))                                 AS VENTAS,
    (VENTAS - C.COSTE_TOTAL) / NULLIFZERO(C.COSTE_TOTAL)             AS ROI
FROM EDW_STG.CAMPANA C
LEFT JOIN EDW_MKT.RESPUESTA_CAMPANA R
  ON R.ID_CAMPANA = C.ID_CAMPANA
GROUP BY 1,2,3,4;

REPLACE VIEW EDW_MKT.V_TOP_CAMPANAS_CANAL AS
SEL CANAL, ID_CAMPANA, NOMBRE_CAMPANA, ROI,
    RANK() OVER (PARTITION BY CANAL ORDER BY ROI DESC) AS RANKING
FROM EDW_MKT.V_KPI_CAMPANAS
QUALIFY RANK() OVER (PARTITION BY CANAL ORDER BY ROI DESC) <= 2;
