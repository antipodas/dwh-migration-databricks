/* Segmentacion por valor del cliente (deciles de facturacion del periodo).
   CALL EDW_MKT.SP_SEGMENTACION_VALOR('202609'); */
REPLACE PROCEDURE EDW_MKT.SP_SEGMENTACION_VALOR (IN P_PERIODO CHAR(6))
BEGIN
  DECLARE V_FILAS INTEGER DEFAULT 0;
  DECLARE V_MSG   VARCHAR(500);

  DECLARE EXIT HANDLER FOR SQLEXCEPTION
  BEGIN
    SET V_MSG = 'Error SQLCODE=' || TRIM(CAST(SQLCODE AS VARCHAR(10)));
    INSERT INTO EDW_MKT.LOG_CARGA (PROCESO, PERIODO, ESTADO, FILAS, MENSAJE)
    VALUES ('SP_SEGMENTACION_VALOR', :P_PERIODO, 'ERROR', 0, :V_MSG);
  END;

  DELETE FROM EDW_MKT.SEGMENTO_VALOR WHERE PERIODO = :P_PERIODO;

  INSERT INTO EDW_MKT.SEGMENTO_VALOR
  SELECT :P_PERIODO,
         C.ID_CLIENTE,
         C.SEGMENTO,
         C.PROVINCIA,
         F.FACTURACION,
         QUANTILE(10, F.FACTURACION) + 1                       AS DECIL_VALOR,
         CASE WHEN QUANTILE(10, F.FACTURACION) >= 8 THEN 'ALTO'
              WHEN QUANTILE(10, F.FACTURACION) >= 4 THEN 'MEDIO'
              ELSE 'BAJO' END                                  AS TRAMO_VALOR
  FROM EDW_MKT.V_CLIENTE_VIGENTE C
  INNER JOIN (SEL ID_CLIENTE, SUM(IMPORTE_TOTAL) AS FACTURACION
              FROM EDW_STG.FACTURA
              WHERE PERIODO = :P_PERIODO
              GROUP BY 1) F
     ON F.ID_CLIENTE = C.ID_CLIENTE;

  SET V_FILAS = ACTIVITY_COUNT;

  INSERT INTO EDW_MKT.LOG_CARGA (PROCESO, PERIODO, ESTADO, FILAS, MENSAJE)
  VALUES ('SP_SEGMENTACION_VALOR', :P_PERIODO, 'OK', :V_FILAS, 'Deciles de valor');
END;
