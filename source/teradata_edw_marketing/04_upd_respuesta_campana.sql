/* Actualizacion diaria de respuestas de campana (upsert al estilo Teradata clasico).
   1) tabla volatil con los contactos del dia
   2) UPDATE ... FROM para los existentes
   3) INSERT de los nuevos */
CREATE VOLATILE MULTISET TABLE VT_CONTACTOS AS
(
  SEL  K.ID_CAMPANA,
       K.ID_CLIENTE,
       K.CANAL,
       K.FECHA_CONTACTO,
       COALESCE(K.RESPUESTA, '?')        AS IND_RESPUESTA,
       NULLIFZERO(K.IMPORTE_VENTA)       AS IMPORTE_VENTA
  FROM EDW_STG.CONTACTO_CAMPANA K
  INNER JOIN EDW_STG.CAMPANA C
     ON C.ID_CAMPANA = K.ID_CAMPANA
  WHERE K.FECHA_CONTACTO <= DATE '2026-10-31'
)
WITH DATA
PRIMARY INDEX (ID_CAMPANA, ID_CLIENTE)
ON COMMIT PRESERVE ROWS;

UPD R
FROM EDW_MKT.RESPUESTA_CAMPANA R, VT_CONTACTOS V
SET IND_RESPUESTA       = V.IND_RESPUESTA,
    IMPORTE_VENTA       = V.IMPORTE_VENTA,
    FECHA_ACTUALIZACION = DATE '2026-10-31'
WHERE R.ID_CAMPANA = V.ID_CAMPANA
  AND R.ID_CLIENTE = V.ID_CLIENTE
  AND (R.IND_RESPUESTA <> V.IND_RESPUESTA OR R.IND_RESPUESTA IS NULL);

INS INTO EDW_MKT.RESPUESTA_CAMPANA
SEL V.ID_CAMPANA, V.ID_CLIENTE, V.CANAL, V.FECHA_CONTACTO, V.IND_RESPUESTA, V.IMPORTE_VENTA, DATE '2026-10-31'
FROM VT_CONTACTOS V
WHERE NOT EXISTS (SEL 1 FROM EDW_MKT.RESPUESTA_CAMPANA R
                  WHERE R.ID_CAMPANA = V.ID_CAMPANA AND R.ID_CLIENTE = V.ID_CLIENTE);

COLLECT STATISTICS ON EDW_MKT.RESPUESTA_CAMPANA;
DROP TABLE VT_CONTACTOS;
