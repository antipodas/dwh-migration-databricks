CREATE MULTISET TABLE EDW_MKT.USO_MENSUAL ,FALLBACK ,
     NO BEFORE JOURNAL,
     NO AFTER JOURNAL,
     CHECKSUM = DEFAULT,
     DEFAULT MERGEBLOCKRATIO
     (
      PERIODO CHAR(6) CHARACTER SET LATIN NOT CASESPECIFIC NOT NULL,
      PERIODO_DT DATE FORMAT 'YYYY-MM-DD' NOT NULL,
      ID_CLIENTE INTEGER NOT NULL,
      SEGMENTO CHAR(3) CHARACTER SET LATIN NOT CASESPECIFIC COMPRESS ('RES','PYM','EMP'),
      DIAS_CON_USO SMALLINT,
      GB_DATOS DECIMAL(12,3),
      MIN_VOZ DECIMAL(12,2),
      NUM_SMS INTEGER COMPRESS 0,
      IMPORTE_EXTRA DECIMAL(12,2) COMPRESS 0.00,
      FLAG_HEAVY_USER BYTEINT COMPRESS (0,1),
      FECHA_PROCESO TIMESTAMP(0) DEFAULT CURRENT_TIMESTAMP(0))
PRIMARY INDEX NUPI_USO_MENSUAL ( ID_CLIENTE )
PARTITION BY RANGE_N(PERIODO_DT BETWEEN DATE '2024-01-01' AND DATE '2027-12-31' EACH INTERVAL '1' MONTH,
                     NO RANGE);

CREATE SET TABLE EDW_MKT.RESPUESTA_CAMPANA ,FALLBACK ,
     NO BEFORE JOURNAL,
     NO AFTER JOURNAL
     (
      ID_CAMPANA INTEGER NOT NULL,
      ID_CLIENTE INTEGER NOT NULL,
      CANAL VARCHAR(10) CHARACTER SET LATIN NOT CASESPECIFIC,
      FECHA_CONTACTO DATE FORMAT 'YYYY-MM-DD',
      IND_RESPUESTA CHAR(1) CHARACTER SET LATIN NOT CASESPECIFIC COMPRESS ('S','N','?'),
      IMPORTE_VENTA DECIMAL(10,2),
      FECHA_ACTUALIZACION DATE FORMAT 'YYYY-MM-DD')
UNIQUE PRIMARY INDEX UPI_RESP_CAMPANA ( ID_CAMPANA ,ID_CLIENTE );

CREATE MULTISET TABLE EDW_MKT.SEGMENTO_VALOR ,NO FALLBACK
     (
      PERIODO CHAR(6) CHARACTER SET LATIN NOT CASESPECIFIC NOT NULL,
      ID_CLIENTE INTEGER NOT NULL,
      SEGMENTO CHAR(3) CHARACTER SET LATIN NOT CASESPECIFIC,
      PROVINCIA VARCHAR(40) CHARACTER SET LATIN NOT CASESPECIFIC,
      FACTURACION DECIMAL(12,2),
      DECIL_VALOR BYTEINT,
      TRAMO_VALOR VARCHAR(10) CHARACTER SET LATIN NOT CASESPECIFIC)
PRIMARY INDEX ( ID_CLIENTE )
INDEX IDX_SEG_PERIODO ( PERIODO );

CREATE MULTISET TABLE EDW_MKT.LOG_CARGA ,NO FALLBACK
     (
      PROCESO VARCHAR(60) CHARACTER SET LATIN NOT CASESPECIFIC,
      PERIODO CHAR(6) CHARACTER SET LATIN NOT CASESPECIFIC,
      ESTADO VARCHAR(10) CHARACTER SET LATIN NOT CASESPECIFIC,
      FILAS INTEGER,
      MENSAJE VARCHAR(500) CHARACTER SET UNICODE NOT CASESPECIFIC,
      TS_LOG TIMESTAMP(0) DEFAULT CURRENT_TIMESTAMP(0))
PRIMARY INDEX ( PROCESO );

COLLECT STATISTICS COLUMN (ID_CLIENTE), COLUMN (PERIODO_DT) ON EDW_MKT.USO_MENSUAL;
COLLECT STATISTICS COLUMN (ID_CAMPANA) ON EDW_MKT.RESPUESTA_CAMPANA;
