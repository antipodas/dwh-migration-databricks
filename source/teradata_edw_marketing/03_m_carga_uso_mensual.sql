/* Macro de carga mensual del uso por cliente.
   Se lanza desde la cadena BTEQ nocturna:  EXEC EDW_MKT.M_CARGA_USO_MENSUAL('202609');  */
REPLACE MACRO EDW_MKT.M_CARGA_USO_MENSUAL (P_PERIODO CHAR(6)) AS
(
  DEL FROM EDW_MKT.USO_MENSUAL WHERE PERIODO = :P_PERIODO;

  INS INTO EDW_MKT.USO_MENSUAL
     (PERIODO, PERIODO_DT, ID_CLIENTE, SEGMENTO, DIAS_CON_USO, GB_DATOS, MIN_VOZ,
      NUM_SMS, IMPORTE_EXTRA, FLAG_HEAVY_USER)
  SEL
      :P_PERIODO,
      CAST(:P_PERIODO || '01' AS DATE FORMAT 'YYYYMMDD'),
      U.ID_CLIENTE,
      C.SEGMENTO,
      COUNT(DISTINCT U.FECHA_USO),
      ZEROIFNULL(SUM(U.MB_DATOS)) / 1024,
      ZEROIFNULL(SUM(U.MIN_VOZ)),
      ZEROIFNULL(SUM(U.NUM_SMS)),
      CAST(ZEROIFNULL(SUM(U.IMPORTE_EXTRA)) AS DECIMAL(12,2)),
      CASE WHEN SUM(U.MB_DATOS) / 1024 > 20 THEN 1 ELSE 0 END
  FROM EDW_STG.USO_DIARIO U
  INNER JOIN EDW_MKT.V_CLIENTE_VIGENTE C
     ON C.ID_CLIENTE = U.ID_CLIENTE
  WHERE U.FECHA_USO BETWEEN CAST(:P_PERIODO || '01' AS DATE FORMAT 'YYYYMMDD')
                        AND ADD_MONTHS(CAST(:P_PERIODO || '01' AS DATE FORMAT 'YYYYMMDD'), 1) - 1
  GROUP BY 1,2,3,4;

  INS INTO EDW_MKT.LOG_CARGA (PROCESO, PERIODO, ESTADO, FILAS, MENSAJE)
  SEL 'M_CARGA_USO_MENSUAL', :P_PERIODO, 'OK', COUNT(*), 'Carga mensual de uso'
  FROM EDW_MKT.USO_MENSUAL WHERE PERIODO = :P_PERIODO;
);
